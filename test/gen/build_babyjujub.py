"""Generates src/fields/SCL_babyjujub.sol: BabyJubJub (circomlib) seen as a short Weierstrass curve with a = -3.

Edwards 168700 x^2 + y^2 = 1 + 168696 x^2 y^2 over F_r (r = order of BN254) -> Montgomery -> Weierstrass,
rescaled by mu (mu^4 = -3/a_w) to get a = -3, so the a = -3 loops of the SCL engines apply.
The generator is the image of circomlib Base8, the order n is the prime subgroup order l.
usage: python3 build_babyjujub.py <SCL_babyjujub.sol>"""
import sys

from bjj import r, l, AE, DE, B8, G, MU2, MU3, A3MU2, a_w, b_iso, ed2w, w_mul, w_on

H = lambda v: "0x%064x" % v

i2, i3 = pow(2, -1, l), pow(3, -1, l)
G128 = w_mul(1 << 128, G)
assert w_on(G) and w_on(G128) and ed2w(B8) == G and w_mul(l, G) is None

# keys Q = +/-c.G making the table of ecGenMulmuladdB4W degenerate, rewritten as (u + c.v).G
small = []
for c in (1, 2, 3, i2, 3 * i2 % l, i3, 2 * i3 % l):
    P = w_mul(c, G)
    small.append((c, P))

SMALL = "\n".join(
    f"uint256 constant _SMALL{k}_X = {H(P[0])};\nuint256 constant _SMALL{k}_Y = {H(P[1])};\n"
    f"uint256 constant _SMALL{k}_C = {H(c)};"
    for k, (c, P) in enumerate(small, 1)
)

